/* Give the extension a stable identity.

   An unpacked extension's id is derived from wherever it happens to sit on
   disk, so it is different for every developer and different again the moment
   somebody moves the folder. That makes the extension untestable: nothing can
   navigate to `chrome-extension://<id>/popup.html` without first knowing the
   id, and there is no way to ask for it when the manifest declares no
   background worker.

   A `key` in the manifest fixes the id to the public key instead. This is the
   documented mechanism and it is what it is for. The Chrome Web Store issues
   its own id on upload and ignores this one, so it costs nothing in production.

   Run once. The public half goes in the manifest and is committed. The private
   half is only needed to sign a self-hosted .crx, is written outside version
   control, and can be regenerated by rerunning this if that day never comes. */

import { generateKeyPairSync, createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const MANIFEST = "extension/manifest.json";
const PRIVATE = "extension-signing-key.pem";

const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));

if (manifest.key && !process.argv.includes("--force")) {
  console.log("  manifest already has a key. Pass --force to replace it.");
  console.log("  id: " + idFor(manifest.key));
  process.exit(0);
}

const { publicKey, privateKey } = generateKeyPairSync("rsa", {
  modulusLength: 2048,
  publicKeyEncoding: { type: "spki", format: "der" },
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
});

const encoded = publicKey.toString("base64");

/* Chrome's id: the first sixteen bytes of the key's SHA-256, each nibble
   mapped onto a to p. Hexadecimal with a different alphabet, because an id
   that could be mistaken for a hash invites people to try to reverse it. */
function idFor(base64Key) {
  const hash = createHash("sha256").update(Buffer.from(base64Key, "base64")).digest();
  let id = "";
  for (let i = 0; i < 16; i++) {
    id += String.fromCharCode(97 + (hash[i] >> 4));
    id += String.fromCharCode(97 + (hash[i] & 0x0f));
  }
  return id;
}

manifest.key = encoded;
writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + "\n");

if (!existsSync(PRIVATE) || process.argv.includes("--force")) {
  writeFileSync(PRIVATE, privateKey);
}

console.log("  extension id: " + idFor(encoded));
console.log("  public key written to " + MANIFEST);
console.log("  private key written to " + PRIVATE + " (gitignored, only needed for a self-hosted .crx)");
